// ── ชั่วโมงประมาณการ (Estimated Work Entries) ─────────────────────────
// เป็น "ชั่วโมงประมาณการรายวัน" ที่กระจายมาจาก estimatedHours ของแต่ละงาน
// ลงวันที่ทำงาน (จันทร์-ศุกร์) ระหว่าง startDate–dueDate แบบ deterministic (ไม่ใช้สุ่ม)
// ไม่ใช่บันทึกเวลาทำงานจริง — UI ต้องแสดงป้าย "ชั่วโมงประมาณการ" เสมอ
function toDateString(date) {
  return `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, '0')}-${String(date.getDate()).padStart(2, '0')}`;
}

function buildEstimatedWorkEntries(tasks) {
  const entries = [];
  tasks.forEach((task) => {
    const total = Number(task.estimatedHours);
    // งานที่ไม่มีผู้รับผิดชอบ/วันที่/ชั่วโมงที่ใช้ไม่ได้ จะไม่ถูกนับ (ไม่ตีความเป็น 0 เงียบ ๆ)
    if (!task.assigneeId || !task.startDate || !task.dueDate) return;
    if (!Number.isFinite(total) || total <= 0) return;

    const start = new Date(`${task.startDate}T00:00:00`);
    const end = new Date(`${task.dueDate}T00:00:00`);
    if (Number.isNaN(start.getTime()) || Number.isNaN(end.getTime()) || end < start) return;

    // เก็บเฉพาะวันทำงาน จันทร์-ศุกร์ (กระจายชั่วโมงตามแบบแผนการทำงานจริง)
    const workdays = [];
    for (const d = new Date(start); d <= end && workdays.length < 120; d.setDate(d.getDate() + 1)) {
      const dow = d.getDay();
      if (dow !== 0 && dow !== 6) workdays.push(toDateString(d));
    }
    if (workdays.length === 0) return;

    // แบ่งชั่วโมงลงเป็นครึ่งชั่วโมง เศษคิวเพิ่มให้วันแรก ๆ ตามลำดับ (deterministic)
    const base = Math.floor((total / workdays.length) * 2) / 2;
    let remainder = Math.round((total - base * workdays.length) * 2);
    workdays.forEach((date) => {
      let hours = base;
      if (remainder >= 1) {
        hours += 0.5;
        remainder -= 1;
      }
      if (hours > 0) {
        entries.push({
          id: `we-${task.id}-${date}`,
          employeeId: task.assigneeId,
          taskId: task.id,
          projectId: task.projectId,
          date,
          hours,
        });
      }
    });
  });
  return entries;
}

